// The Oefenschrift mark, chosen on 23 September 2026 after the style exploration: a yellow
// speech bubble saying "oe" — the first sound a learner meets that is only Dutch — beside the
// name, both in Nunito 900. The bubble has a sharp tail, is a little larger than the capitals
// and hangs below them; the user tuned it by eye in the development dock (bubble 117%, its
// "oe" 93%, 6 units lower) after comparing six tails and eighteen faces (bubble.mjs) and
// seventeen other ideas (concepts.mjs). Writes app/components/logo.ts — the name follows
// currentColor, the bubble --action, and the "oe" stays dark on the yellow in both themes —
// and the site's icons in assets/icons: for browser tabs the bare bubble (icon.svg,
// favicon.ico with 16, 32 and 48 pixels, icon-32.png), for phones the bubble on an ink ground
// (apple-touch-icon.png, icon-192.png, icon-512.png, icon-maskable-512.png, listed with
// site.webmanifest) — rasterised here as icon.mjs did: filled shapes sampled sixteen times
// per pixel, so transparent edges and a rounded tile's corners stay clean.
//
//   npm install --no-save opentype.js@1.3.4
//   node docs/logos/mark.mjs
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { execFileSync } from 'node:child_process';
import { loadFont, layout, bounds, flatten, inside, round } from './lib.mjs';
const here = path.dirname(new URL(import.meta.url).pathname),
  root = path.resolve(here, '../..');
const heavy = await loadFont('Nunito', 900),
  reference = await loadFont('Nunito', 800);
const capOf = (font) => -font.charToGlyph('H').getPath(0, 0, 100).getBoundingBox().y1;
// The bubble as bubble.mjs drew it, in the 100-unit em of the name with the baseline at 0.
const L = 0,
  R = 86,
  T = -75,
  B = -7,
  RAD = 21,
  GAP = 20,
  TIP = [
    [18, B - 4],
    [12, B + 17],
    [38, B - 4],
  ];
// The user's proportions from the dock.
const SIZE = 1.17,
  LETTERS = 0.93,
  DROP = 6;
const MIDDLE = (T + B) / 2,
  CENTRE = (L + R) / 2;
const body =
  `M${L + RAD} ${T}H${R - RAD}A${RAD} ${RAD} 0 0 1 ${R} ${T + RAD}V${B - RAD}A${RAD} ${RAD} 0 0 1 ${R - RAD} ${B}` +
  `H${L + RAD}A${RAD} ${RAD} 0 0 1 ${L} ${B - RAD}V${T + RAD}A${RAD} ${RAD} 0 0 1 ${L + RAD} ${T}Z`;
const tip = `M${TIP.map(([x, y]) => `${x} ${y}`).join('L')}Z`;
// The name at Nunito 800's capital height, as the faces were compared; the "oe" at 42% of
// the bubble's height, centred a little above its middle.
const word = layout(heavy, 'Oefenschrift', { x: R + GAP, size: (100 * capOf(reference)) / capOf(heavy) }),
  probe = bounds(layout(heavy, 'oe', { size: 100 }), 0),
  scale = (0.42 * (B - T)) / (probe.y2 - probe.y1),
  oe = layout(heavy, 'oe', {
    size: 100 * scale,
    x: CENTRE - ((probe.x2 - probe.x1) * scale) / 2 - probe.x1 * scale,
    y: MIDDLE - 1 + ((probe.y2 - probe.y1) * scale) / 2 - probe.y2 * scale,
  });
const letters = `translate(${round(CENTRE * (1 - LETTERS))} ${round(MIDDLE * (1 - LETTERS))}) scale(${LETTERS})`,
  bubble = `translate(${round(R * (1 - SIZE))} ${round(MIDDLE * (1 - SIZE) + DROP)}) scale(${SIZE})`,
  oeData = oe.map((g) => g.d).join('');
// The lockup's box: the bubble grows away from the name and hangs below the baseline.
const wb = bounds(word, 0),
  x1 = Math.min(R - SIZE * (R - L), 0) - 3,
  y1 = Math.min(wb.y1, MIDDLE + SIZE * (T - MIDDLE) + DROP) - 3,
  x2 = wb.x2 + 3,
  y2 = Math.max(wb.y2, MIDDLE + SIZE * (TIP[1][1] - MIDDLE) + DROP) + 3;
const markup =
  `<g transform="${bubble}"><g class="bubble-motion"><path class="accent" d="${body}"/><path class="accent" d="${tip}"/>` +
  `<g class="letters-motion"><path class="on-accent" transform="${letters}" d="${oeData}"/></g></g></g>` +
  `<path class="ink" d="${word.map((g) => g.d).join('')}"/>`;
const file = path.join(root, 'app/components/logo.ts');
fs.writeFileSync(
  file,
  `// Generated by docs/logos/mark.mjs: the Oefenschrift mark, a yellow speech bubble saying "oe"
// beside the name in Nunito 900. Path markup in a 100-unit em; the name follows currentColor,
// the bubble --action and the "oe" (on-accent) stays dark on it. bubble-motion and
// letters-motion are the groups the click animation moves.
export const logo = ${JSON.stringify(
    {
      id: 'oefenschrift',
      name: 'Oefenschrift',
      viewBox: [x1, y1, x2 - x1, y2 - y1].map(round).join(' '),
      markup,
    },
    null,
    2,
  )};
`,
);
execFileSync('npx', ['prettier', '--write', file], { cwd: root, stdio: 'ignore' });

// ---- The site's icons ----------------------------------------------------------------
// In a browser tab the bubble stands on its own, as large as the square allows: a tab icon
// is too small for a tile around it (the user found the ink tile left the bubble cramped).
// On phones and launchers, where the icon is large, it sits on an ink ground with room
// around it: the Android "any" icons on a rounded tile with transparent corners (22%
// radius), a full square for the iPhone home screen (iOS rounds it itself and paints
// transparent corners black), and a roomier full square for Android's maskable icon,
// whose launcher cuts it to a circle or squircle with the bubble inside the safe circle.
const INK = '#221f1a',
  ACCENT = '#efbf24',
  RADIUS = 0.22,
  BARE = 88,
  TILE = 110,
  TOUCH = 128,
  MASKABLE = 160,
  // The centre of the bubble with its tail, and a little higher on a ground, where the tail
  // may reach into the lower margin.
  BARE_CY = (T + TIP[1][1]) / 2,
  CY = -36;
const out = path.join(root, 'assets/icons');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(
  path.join(out, 'icon.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${round(CENTRE - BARE / 2)} ${round(BARE_CY - BARE / 2)} ${BARE} ${BARE}"><path fill="${ACCENT}" d="${body}"/><path fill="${ACCENT}" d="${tip}"/><path fill="${INK}" transform="${letters}" d="${oeData}"/></svg>`,
);
// Point tests in the bubble's own units: the tile, the bubble's body and tail, the "oe".
const oePolygons = oe.flatMap((g) => flatten(g.path));
const inRounded = (px, py, left, top, width, height, r) => {
  const qx = Math.max(left + r - px, px - (left + width - r), 0),
    qy = Math.max(top + r - py, py - (top + height - r), 0);
  return px >= left && px <= left + width && py >= top && py <= top + height && Math.hypot(qx, qy) <= r;
};
const inTriangle = (px, py, [[ax, ay], [bx, by], [cx, cy]]) => {
  const d1 = (px - bx) * (ay - by) - (ax - bx) * (py - by),
    d2 = (px - cx) * (by - cy) - (bx - cx) * (py - cy),
    d3 = (px - ax) * (cy - ay) - (cx - ax) * (py - ay);
  return !((d1 < 0 || d2 < 0 || d3 < 0) && (d1 > 0 || d2 > 0 || d3 > 0));
};
const k = LETTERS,
  kx = CENTRE * (1 - k),
  ky = MIDDLE * (1 - k);
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const ink = rgb(INK),
  accent = rgb(ACCENT);
// One raster of `px` pixels showing a square of `side` units around the bubble. `ground`
// paints ink behind it — `radius` 0 fills the whole square, otherwise a rounded tile — and
// without it only the bubble and its "oe" are drawn, on transparency.
function rasterise(px, side, { ground = true, radius = 0, withLetters = true } = {}) {
  const ix = CENTRE - side / 2,
    iy = (ground ? CY : BARE_CY) - side / 2,
    data = Buffer.alloc(px * px * 4),
    step = side / px,
    sub = 4;
  for (let j = 0; j < px; j++)
    for (let i = 0; i < px; i++) {
      let r = 0,
        g = 0,
        b = 0,
        hits = 0;
      for (let sy = 0; sy < sub; sy++)
        for (let sx = 0; sx < sub; sx++) {
          const cx = ix + (i + (sx + 0.5) / sub) * step,
            cy = iy + (j + (sy + 0.5) / sub) * step;
          if (ground && radius && !inRounded(cx, cy, ix, iy, side, side, side * radius)) continue;
          let paint = ground ? ink : null;
          if (inRounded(cx, cy, L, T, R - L, B - T, RAD) || inTriangle(cx, cy, TIP)) paint = accent;
          if (withLetters && paint === accent && inside(oePolygons, (cx - kx) / k, (cy - ky) / k)) paint = ink;
          if (!paint) continue;
          r += paint[0];
          g += paint[1];
          b += paint[2];
          hits++;
        }
      const at = (j * px + i) * 4;
      if (!hits) continue;
      data[at] = Math.round(r / hits);
      data[at + 1] = Math.round(g / hits);
      data[at + 2] = Math.round(b / hits);
      data[at + 3] = Math.round((255 * hits) / (sub * sub));
    }
  return png(px, data);
}
// A PNG: eight-bit RGBA rows with filter 0, deflated.
function png(px, rgba) {
  const chunk = (type, content) => {
    const head = Buffer.concat([Buffer.from(type), content]),
      crc = Buffer.alloc(4),
      length = Buffer.alloc(4);
    crc.writeUInt32BE(zlib.crc32(head));
    length.writeUInt32BE(content.length);
    return Buffer.concat([length, head, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(px, 0);
  ihdr.writeUInt32BE(px, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  const rows = Buffer.alloc(px * (px * 4 + 1));
  for (let j = 0; j < px; j++) rgba.copy(rows, j * (px * 4 + 1) + 1, j * px * 4, (j + 1) * px * 4);
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(rows, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}
fs.writeFileSync(path.join(out, 'apple-touch-icon.png'), rasterise(180, TOUCH));
fs.writeFileSync(path.join(out, 'icon-192.png'), rasterise(192, TILE, { radius: RADIUS }));
fs.writeFileSync(path.join(out, 'icon-512.png'), rasterise(512, TILE, { radius: RADIUS }));
fs.writeFileSync(path.join(out, 'icon-maskable-512.png'), rasterise(512, MASKABLE));
fs.writeFileSync(path.join(out, 'icon-32.png'), rasterise(32, BARE, { ground: false }));
const entries = [
  [16, rasterise(16, BARE, { ground: false })],
  [32, rasterise(32, BARE, { ground: false })],
  [48, rasterise(48, BARE, { ground: false })],
];
const header = Buffer.alloc(6 + 16 * entries.length);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(entries.length, 4);
let offset = header.length;
entries.forEach(([px, image], n) => {
  const at = 6 + 16 * n;
  header.writeUInt8(px, at);
  header.writeUInt8(px, at + 1);
  header.writeUInt16LE(1, at + 4);
  header.writeUInt16LE(32, at + 6);
  header.writeUInt32LE(image.length, at + 8);
  header.writeUInt32LE(offset, at + 12);
  offset += image.length;
});
fs.writeFileSync(path.join(out, 'favicon.ico'), Buffer.concat([header, ...entries.map(([, image]) => image)]));
// The web app manifest, so a phone's home screen gets the rounded icon. Paths are relative to
// the manifest, which works under a base path too. "standalone" lets Android install the site
// with the maskable icon as a proper launcher icon.
fs.writeFileSync(
  path.join(out, 'site.webmanifest'),
  JSON.stringify(
    {
      name: 'Oefenschrift',
      short_name: 'Oefenschrift',
      description: 'Gratis oefenen voor het inburgeringsexamen: lezen, luisteren, schrijven, spreken en KNM.',
      lang: 'nl',
      start_url: './',
      scope: './',
      display: 'standalone',
      background_color: '#ffffff',
      theme_color: '#f7f6f2',
      icons: [
        { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
        { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
        { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
      ],
    },
    null,
    2,
  ) + '\n',
);
console.log(`logo.ts ${[x1, y1, x2 - x1, y2 - y1].map(round).join(' ')}; icons and manifest written to assets/icons`);
